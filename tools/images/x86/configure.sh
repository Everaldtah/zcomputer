#!/bin/sh
# Runs inside the 32-bit Alpine chroot (called by build-image.sh after the
# packages and tools/images/x86/overlay are in place). Configures services,
# the z user, the XFCE session, the kernel command line and extlinux.
set -eu

VERSION=${IMAGE_VERSION:-dev}
BRANCH=${ALPINE_BRANCH:-v3.22}
MIRROR=${ALPINE_MIRROR:-https://dl-cdn.alpinelinux.org/alpine}
KERNEL_FLAVOR=virt
CMDLINE="root=/dev/sda1 rw rootfstype=ext4 rootflags=noatime modules=sd-mod,ext4 console=tty0 console=ttyS0,115200 video=1024x768-32 init_on_free=1 mitigations=off"

step() { printf '\n--> %s\n' "$*"; }

step "apk repositories"
printf '%s/%s/main\n%s/%s/community\n' "$MIRROR" "$BRANCH" "$MIRROR" "$BRANCH" > /etc/apk/repositories
cat /etc/apk/repositories

step "identity: hostname, hosts, machine-id, image version"
echo z-alpine > /etc/hostname
printf '127.0.0.1\tlocalhost localhost.localdomain z-alpine\n::1\t\tlocalhost localhost.localdomain\n' > /etc/hosts
dbus-uuidgen > /etc/machine-id
mkdir -p /var/lib/dbus && ln -sf /etc/machine-id /var/lib/dbus/machine-id
cat > /etc/zcomputer-image <<EOF
ID=z-alpine-desktop-x86
NAME="Z Alpine Desktop (x86)"
VERSION=$VERSION
ALPINE=$(cat /etc/alpine-release)
BUILT=$(date -u +%Y-%m-%dT%H:%M:%SZ)
EOF
mkdir -p /mnt/host

step "permissions of overlay scripts"
chmod 0755 /etc/init.d/zguest /etc/init.d/zshare /usr/local/sbin/zc-display-setup /usr/local/bin/z-net-reset /usr/local/bin/zg
chmod 0440 /etc/sudoers.d/wheel
chmod 0644 /etc/fstab /etc/inittab /etc/network/interfaces /etc/motd /etc/issue

step "user z (password z, wheel = passwordless sudo)"
for g in autologin nopasswdlogin; do getent group "$g" >/dev/null || addgroup -S "$g"; done
adduser -D -s /bin/bash -g "Z" z
echo 'z:z' | chpasswd
for g in wheel video input audio autologin nopasswdlogin; do addgroup z "$g" 2>/dev/null || adduser z "$g"; done
id z
grep -q '^z:\$' /etc/shadow || { echo "password for z was not set" >&2; exit 1; }
passwd -l root >/dev/null 2>&1 || true
cp -a /etc/skel/. /home/z/
x=/home/z/.config/xfce4/xfconf/xfce-perchannel-xml
mkdir -p "$x"
cp /etc/zcomputer/xfconf/*.xml "$x/"
chown -R z:z /home/z

step "OpenRC runlevels"
add() { # add LEVEL SERVICE... ; a trailing '?' marks a service that may be absent
    lvl=$1; shift
    for s in "$@"; do
        n=${s%\?}
        if [ ! -e "/etc/init.d/$n" ]; then
            [ "$n" != "$s" ] && { echo "  (no $n, skipped)"; continue; }
            echo "missing init script: $n" >&2; exit 1
        fi
        rc-update add "$n" "$lvl" >/dev/null
    done
}
add sysinit devfs dmesg cgroups udev udev-trigger udev-settle
add boot modules sysctl hostname bootmisc syslog hwclock seedrng?
add default networking udev-postmount dbus elogind zshare zguest lightdm
add shutdown killprocs mount-ro savecache?
rc-update show

step "Xorg drivers"
ls /usr/lib/xorg/modules/drivers/ /usr/lib/xorg/modules/input/

step "kernel ($KERNEL_FLAVOR) + initramfs"
krel=$(cat /usr/share/kernel/$KERNEL_FLAVOR/kernel.release)
echo "kernel release $krel"
cat > /etc/mkinitfs/mkinitfs.conf <<'EOF'
features="ata base ext4 scsi virtio"
EOF
mkinitfs -o /boot/initramfs-$KERNEL_FLAVOR "$krel"
ls -la /boot

step "extlinux.conf (update-extlinux keeps it: overwrite=0)"
cat > /etc/update-extlinux.conf <<EOF
# Z Computer: /boot/extlinux.conf is written by the image build; keep it on kernel upgrades.
overwrite=0
default_kernel_opts="$CMDLINE"
modules=sd-mod,ext4
root=/dev/sda1
hidden=1
timeout=1
default=$KERNEL_FLAVOR
serial_port=0
serial_baud=115200
EOF
cat > /boot/extlinux.conf <<EOF
# Z Alpine Desktop (x86) -- generated by tools/images/x86/configure.sh
SERIAL 0 115200
DEFAULT z
PROMPT 0
TIMEOUT 0

LABEL z
  MENU LABEL Z Alpine Desktop (x86), linux-$KERNEL_FLAVOR $krel
  LINUX /boot/vmlinuz-$KERNEL_FLAVOR
  INITRD /boot/initramfs-$KERNEL_FLAVOR
  APPEND $CMDLINE
EOF
cat /boot/extlinux.conf

step "caches: fonts, icons, pixbuf loaders, mime"
fc-cache -f >/dev/null 2>&1 || true
for d in /usr/share/icons/*/; do [ -f "$d/index.theme" ] && gtk-update-icon-cache -q -f "$d" 2>/dev/null || true; done
gdk-pixbuf-query-loaders --update-cache 2>/dev/null || true
update-mime-database /usr/share/mime >/dev/null 2>&1 || true
glib-compile-schemas /usr/share/glib-2.0/schemas 2>/dev/null || true

if [ "${PRUNE_GL:-1}" = 1 ]; then
    step "prune the OpenGL stack (Mesa gallium drivers + LLVM + SPIRV-Tools)"
    # xorg-server depends on mesa-egl -> mesa -> llvm. Nothing in this image
    # renders with OpenGL: Xorg uses fbdev with GLX and glamor disabled and
    # xfwm4 compositing is off. `sudo apk fix mesa llvm20-libs` brings it back.
    before=$(du -sm /usr/lib | cut -f1)
    for p in $(apk info 2>/dev/null | grep -E '^(llvm[0-9]+-libs|spirv-tools)$'); do
        apk info -qL "$p" 2>/dev/null | grep -E '^(usr/)?lib/' | while read -r f; do rm -f "/$f"; done
    done
    rm -f /usr/lib/libgallium-*.so
    rm -rf /usr/lib/dri /usr/lib/gbm
    echo "/usr/lib: ${before} MiB -> $(du -sm /usr/lib | cut -f1) MiB"
fi

step "shared-library check"
# Every program and Xorg module must still resolve its libraries. Mesa's own
# GL front ends (libEGL_mesa, libGLX_mesa, ...) and the disabled GLX/glamor
# modules are allowed to miss the pruned gallium/LLVM libraries.
allow='libEGL_mesa|libGLX_mesa|libxatracker|libOSMesa|libgallium|libvulkan_|libglamoregl|/extensions/libglx|/dri/|libgbm'
bad=0
for f in $(find /bin /sbin /usr/bin /usr/sbin /usr/libexec /usr/lib /usr/local/bin -type f \( -perm -u+x -o -name '*.so*' \) 2>/dev/null); do
    [ "$(head -c 4 "$f" 2>/dev/null | od -An -c | tr -d ' ')" = '177ELF' ] || continue
    miss=$(ldd "$f" 2>&1 | grep 'not found' || true)
    [ -z "$miss" ] && continue
    if printf '%s\n' "$f" | grep -Eq "$allow"; then continue; fi
    echo "MISSING LIBS: $f"; printf '%s\n' "$miss" | sed 's/^/    /'
    bad=1
done
[ "$bad" = 0 ] || { echo "shared-library check failed" >&2; exit 1; }
echo "all binaries resolve their libraries"

step "summary"
echo "netsurf: $(ls /usr/bin | grep -i netsurf | tr '\n' ' ')"
/usr/local/bin/zguest --version 2>/dev/null || file /usr/local/bin/zguest 2>/dev/null || true
cat /etc/pam.d/lightdm-autologin 2>/dev/null | sed 's/^/  pam lightdm-autologin: /' || true
du -sm --one-file-system / 2>/dev/null | cut -f1 | sed 's/$/ MiB in rootfs/'
